#!/usr/bin/env python3
"""Generate Codex skill adapters for the plugin's Claude Code commands."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
PLUGIN_ROOT = REPO_ROOT / "plugins" / "ccu"
COMMANDS_ROOT = PLUGIN_ROOT / "commands"
SKILLS_ROOT = PLUGIN_ROOT / "skills"
GENERATED_MARKER = "<!-- Generated by scripts/sync-command-skills.py; do not edit. -->"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated command skills are missing or stale.",
    )
    return parser.parse_args()


def command_metadata(path: Path) -> tuple[str, str]:
    contents = path.read_text(encoding="utf-8")
    if not contents.startswith("---\n"):
        raise ValueError(f"{path} is missing YAML frontmatter")
    end = contents.find("\n---", 4)
    if end == -1:
        raise ValueError(f"{path} has unclosed YAML frontmatter")

    description_match = re.search(
        r"^description:\s*(.+?)\s*$", contents[4:end], flags=re.MULTILINE
    )
    if description_match is None:
        raise ValueError(f"{path} is missing a frontmatter description")

    command_name = path.stem
    skill_name = command_name.replace(":", "-")
    description = description_match.group(1).strip().strip("\"'")
    return skill_name, description


def render(command_path: Path) -> tuple[Path, str]:
    skill_name, description = command_metadata(command_path)
    target = SKILLS_ROOT / skill_name / "SKILL.md"
    relative_command = f"../../commands/{command_path.name}"
    body = f"""---
name: {skill_name}
description: {description}. Codex adapter for the /{command_path.stem} workflow.
---

{GENERATED_MARKER}

# /{command_path.stem}

Read [the shared command workflow]({relative_command}) and
[the Codex compatibility rules](../../CODEX.md) completely, then carry out the
workflow using the current user's request as its arguments.
"""
    return target, body


def main() -> int:
    args = parse_args()
    expected: dict[Path, str] = {}
    for command_path in sorted(COMMANDS_ROOT.glob("t:*.md")):
        target, body = render(command_path)
        expected[target] = body

    stale: list[Path] = []
    for target, body in expected.items():
        if not target.is_file() or target.read_text(encoding="utf-8") != body:
            stale.append(target)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(body, encoding="utf-8")

    generated_dirs = {
        path.parent
        for path in SKILLS_ROOT.glob("t-*/SKILL.md")
        if GENERATED_MARKER in path.read_text(encoding="utf-8")
    }
    obsolete = sorted(generated_dirs - {path.parent for path in expected})

    if args.check and (stale or obsolete):
        for path in stale:
            print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        for path in obsolete:
            print(f"obsolete: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1

    if obsolete:
        print("Obsolete generated skills must be removed manually:", file=sys.stderr)
        for path in obsolete:
            print(f"- {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1

    action = "checked" if args.check else "synced"
    print(f"{action} {len(expected)} command skill adapters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
